"""Export the official Mapzen/AWS SRTM HGT tile as a synchronous shared DEM.
Run: python tools/terrain/build_dem.py
Requires numpy. No interpolation outside source bounds, no site deformation.
The north-to-south source rows map to increasing world Z (north is -Z).
"""
from pathlib import Path
import base64, gzip, hashlib, json, math
import numpy as np
ROOT=Path(__file__).resolve().parents[2]
SOURCE=ROOT/'assets/source/terrain/N34E076.hgt.gz'
OUT=ROOT/'src/world/terrain/suruDEM.generated.js'
RES=1537
CROP=(0,800,3150,3500) # west/north/east/south source pixel coordinates

def main():
    compressed=SOURCE.read_bytes();raw=gzip.decompress(compressed)
    side=math.isqrt(len(raw)//2)
    if side!=3601 or len(raw)!=side*side*2:raise ValueError('Expected complete one-arcsecond HGT')
    original=np.frombuffer(raw,dtype='>i2').reshape(side,side)
    if np.any(original==-32768):raise ValueError('DEM voids require explicit source repair')
    x0,y0,x1,y1=CROP
    xs=np.linspace(x0,x1,RES);ys=np.linspace(y0,y1,RES)
    ix=np.floor(xs).astype(int);iy=np.floor(ys).astype(int)
    tx=xs-ix;ty=ys-iy
    nx=np.minimum(ix+1,side-1);ny=np.minimum(iy+1,side-1)
    top=original[iy[:,None],ix[None,:]]*(1-tx)+original[iy[:,None],nx[None,:]]*tx
    bottom=original[ny[:,None],ix[None,:]]*(1-tx)+original[ny[:,None],nx[None,:]]*tx
    heights=np.rint(top*(1-ty[:,None])+bottom*ty[:,None]).astype('<u2')
    encoded=bytearray()
    for row in heights:
        previous=0
        for value in row:
            value=int(value);delta=value-previous;previous=value
            v=(delta<<1)^(delta>>31)
            while v>=128:encoded.append((v&127)|128);v>>=7
            encoded.append(v)
    west=76+x0/3600;east=76+x1/3600;north=35-y0/3600;south=35-y1/3600
    latitude=(north+south)/2
    width=(east-west)*111320*math.cos(math.radians(latitude));depth=(north-south)*111320
    meta={'id':'suru-zanskar-srtm-v1','name':'Suru–Zanskar Himalayan range','resolution':RES,
      'source':'assets/source/terrain/N34E076.hgt.gz','sourceUrl':'https://elevation-tiles-prod.s3.amazonaws.com/skadi/N34/N34E076.hgt.gz',
      'sourceSha256':hashlib.sha256(compressed).hexdigest(),'sourceBytes':len(compressed),
      'attribution':'Mapzen terrain tiles; SRTM/GMTED elevation data courtesy USGS.',
      'attributionUrl':'https://github.com/tilezen/joerd/blob/master/docs/attribution.md',
      'registryUrl':'https://registry.opendata.aws/terrain-tiles/',
      'sourceCropPixels':list(CROP),'geographicBounds':{'west':west,'east':east,'south':south,'north':north},
      'worldBounds':{'minX':-width/2,'maxX':width/2,'minZ':-depth/2,'maxZ':depth/2},
      'cellMetres':[width/(RES-1),depth/(RES-1)],'blendMetres':6000,
      'heightMin':int(heights.min()),'heightMax':int(heights.max()),'heightUnitMetres':1,
      'encoding':'row-reset delta zigzag LEB128 base64; reconstructed uint16 integer metres',
      'decodedUint16Sha256':hashlib.sha256(heights.tobytes()).hexdigest(),
      'deltaBytes':len(encoded),'floatTextureBytes':RES*RES*4,
      'probes':[[int(x),int(y),int(heights[y,x])] for x,y in [(0,0),(RES-1,RES-1),(768,768),(137,1193),(1109,419)]]}
    js='// Generated by tools/terrain/build_dem.py. Do not edit.\nexport const DEM_METADATA = '+json.dumps(meta,separators=(',',':'))+';\nexport const DEM_DELTA_BASE64 = '+json.dumps(base64.b64encode(encoded).decode())+';\n'
    OUT.write_text(js,encoding='utf-8',newline='\n')
    meta['generatedModuleBytes']=len(js.encode());meta['generatedModuleGzipBytes']=len(gzip.compress(js.encode(),mtime=0))
    (ROOT/'public/assets/terrain/suru-dem.json').write_text(json.dumps(meta,indent=2)+'\n',encoding='utf-8',newline='\n')
    print(json.dumps({k:meta[k] for k in ['worldBounds','cellMetres','heightMin','heightMax','deltaBytes','generatedModuleBytes','generatedModuleGzipBytes','floatTextureBytes']},indent=2))
if __name__=='__main__':main()
