def jet_whine_src(r, n):
    """Compressor/turbine whine: blade-pass harmonics with stage beating, slow FM."""
    t = t_axis(n)
    fm = 1 + 0.0025 * smooth_noise(r, n, 3)
    y = np.zeros(n)
    for f, a in [(1180, 1.0), (2360, 0.55), (1617, 0.35), (3540, 0.22), (2905, 0.18), (4720, 0.1), (590, 0.25)]:
        am = 1 + 0.25 * smooth_noise(r, n, 7)
        y += a * am * osc(f * fm * (1 + r.uniform(-0.002, 0.002)), n)
    band = bp(white(r, n), 1000, 1400, 2) * 0.6 + bp(white(r, n), 3300, 3900, 2) * 0.35
    shaft = 0.25 * osc(148 * fm, n) + 0.12 * osc(296 * fm, n)
    return y * 0.5 + band + shaft


def jet_intake_src(r, n):
    nz = pink(r, n)
    y = resonator(nz, 620, 4) * 1.0 + resonator(nz, 1650, 6) * 0.7 + resonator(nz, 2400, 10) * 0.35
    whistle = osc(3400 * (1 + 0.004 * smooth_noise(r, n, 2)), n) * 0.08 * (1 + 0.5 * smooth_noise(r, n, 4))
    flutter = 1 + 0.18 * smooth_noise(r, n, 11)
    return (y + whistle) * flutter


def jet_roar_src(r, n, low=1.0, crack=1.0):
    """External exhaust roar: broadband jet-mixing noise + crackle, decorrelated stereo."""
    out = np.zeros((n, 2))
    common = colored(r, n, -4.5)
    for c in range(2):
        own = colored(r, n, -4.5)
        x = 0.6 * common + 0.8 * own
        x = peak_eq(x, 180, 5 * low, 0.7)
        x = peak_eq(x, 900, 2, 0.8)
        x = lp(x, 5500, 2)
        cr = hp(crackle(r, n, 260 * crack, alpha=2.0), 700, 2)
        cr /= (np.std(cr) + 1e-9)
        sw = 1 + 0.12 * smooth_noise(r, n, 1.5)
        out[:, c] = (x + 0.35 * crack * cr) * sw
    return out


def jet_rumble_src(r, n):
    out = np.zeros((n, 2))
    hum = 0.25 * osc(55 * (1 + 0.01 * smooth_noise(r, n, 1)), n) + 0.1 * osc(110, n)
    for c in range(2):
        x = lp(brown(r, n), 160, 4) * 1.2 + lp(pink(r, n), 600, 2) * 0.25
        out[:, c] = x + hum
    return out


def ab_src(r, n):
    out = jet_roar_src(r, n, low=1.6, crack=1.8)
    flame = 1 + 0.25 * smooth_noise(r, n, 12) + 0.15 * smooth_noise(r, n, 4)
    sub = lp(brown(r, n), 90, 4) * 1.4
    return lp(out, 3800, 2) * flame[:, None] + stereo(sub)


def loopify(fn, seconds, xfade=0.35, seed=0):
    r = rng(seed)
    L, X = secs(seconds), secs(xfade)
    return make_loop(fn(r, L + X), L, X)


def ab_lightoff(r, v):
    n = secs(2.4)
    t = t_axis(n)
    f = 85 * np.exp(-t / 0.12) + 32
    thump = osc(f, n) * env_exp(n, 0.35, 0.004) * 1.4
    burst = bp(white(r, n), 90, 900, 2) * env_points(n, [(0, 0), (0.015, 1), (0.1, 0.7), (0.7, 0.15), (2.4, 0)])
    roar = mono(ab_src(r, n)) * env_points(n, [(0, 0), (0.12, 0.2), (0.5, 0.6), (1.4, 0.35), (2.4, 0)]) * 0.5
    pop = hp(white(r, n), 1500) * env_exp(n, 0.006) * 0.6
    y = saturate(thump + burst * 0.9 + roar + pop, 1.5)
    return stereo(y, np.roll(y, secs(0.004)))


# ================================================================== airflow
def wind_src(r, n):
    out = np.zeros((n, 2))
    swell = 0.75 + 0.25 * smooth_noise(r, n, 0.6)
    for c in range(2):
        x = lp(pink(r, n), 1400, 2) + 0.25 * bp(white(r, n), 2000, 5000, 1)
        out[:, c] = x * swell * (1 + 0.1 * smooth_noise(r, n, 3))
    return out


def buffet_src(r, n):
    out = np.zeros(n)
    pos = 0
    while pos < n:
        pos += int(SR / r.uniform(9, 22))
        k = secs(0.09)
        f0 = r.uniform(38, 85)
        bump = osc(f0, k) * env_exp(k, 0.03, 0.003) * r.uniform(0.4, 1.0)
        mix_at(out, bump, pos)
        if r.random() < 0.45:
            ra = modal(secs(0.05), [(r.uniform(700, 1800), 0.012, 1), (r.uniform(2500, 4200), 0.008, 0.6)], r)
            mix_at(out, ra * r.uniform(0.05, 0.18), pos + int(r.integers(0, 300)))
    base = lp(brown(r, n), 120, 2) * 0.5
    y = out + base
    return stereo(y, np.roll(y, 211))


def g_breath(r, v):
    """Anti-G straining manoeuvre through an oxygen mask: strain grunt, sharp exhale, quick inhale."""
    n = secs(1.15)
    y = np.zeros(n)
    f0 = [108, 118, 102][v % 3]
    k = secs(0.32)
    jit = 1 + 0.03 * smooth_noise(r, k, 30)
    pulse = osc(f0 * jit, k, 'saw')
    g = pulse * env_points(k, [(0, 0), (0.03, 1), (0.25, 0.8), (0.32, 0)])
    vowel = resonator(g, 560, 5) + 0.7 * resonator(g, 1050, 6) + 0.35 * resonator(g, 2450, 8)
    vowel += 0.25 * bp(white(r, k), 500, 3000) * env_points(k, [(0, 0), (0.05, 1), (0.32, 0.3)])
    mix_at(y, vowel * 0.8, 0)
    k2 = secs(0.18)
    ex = bp(white(r, k2), 400, 2600, 2) * env_points(k2, [(0, 0), (0.01, 1), (0.18, 0)])
    mix_at(y, resonator(ex, 1200, 2) * 1.6 + ex * 0.4, secs(0.33))
    k3 = secs(0.4)
    inh = bp(white(r, k3), 600, 3500, 2) * env_points(k3, [(0, 0), (0.12, 1), (0.4, 0)])
    mix_at(y, inh * 0.45, secs(0.6))
    click = modal(secs(0.02), [(2400, 0.004, 1), (4100, 0.003, 0.5)], r)
    mix_at(y, click * 0.15, secs(0.58))
    y = bp(y, 180, 4200, 2)  # mask
    y = peak_eq(y, 1300, 4, 1.2)
    return y


# ==================================================================== guns
GUN_PERIOD = 847  # samples @48k -> 3400 rounds/min, GSh-23L


def gun_shot(r, strength=1.0, interior=0.5):
    n = secs(0.09)
    t = t_axis(n)
    blast = (hp(white(r, n), 300, 2) * env_exp(n, 0.0045, 0.0002) * 1.4
             + lp(white(r, n), 2500) * env_exp(n, 0.012) * 0.8)
    nwave = np.zeros(n)
    k = secs(0.0012)
    nwave[:k] = np.linspace(1, -1, k) * np.hanning(k + 2)[1:-1] ** 0.3
    mech = modal(n, [(r.uniform(160, 200), 0.018, 0.9), (r.uniform(400, 460), 0.012, 0.6),
                     (r.uniform(880, 980), 0.008, 0.4), (r.uniform(2100, 2500), 0.004, 0.25)], r)
    thump = osc(70 * np.exp(-t / 0.02) + 45, n) * env_exp(n, 0.02) * 0.9
    return (blast + nwave * 0.8 + mech * interior + thump) * strength


def gun_loop(r, v):
    shots = 48
    L = GUN_PERIOD * shots
    out = np.zeros((L + secs(0.2), 2))
    for i in range(shots):
        s = gun_shot(r, 10 ** (r.uniform(-1.5, 1.0) / 20))
        pos = i * GUN_PERIOD + int(r.integers(-12, 12))
        mix_at(out, stereo(s, s * 0.96), max(0, pos))
    # circular wrap of tails
    tail = out[L:].copy()
    out = out[:L]
    out[:len(tail)] += tail
    body = stereo(lp(brown(r, L), 220, 2) * 0.35)
    out = out + body
    out = saturate(out * 0.6, 1.6)
    return out


def gun_start(r, v):
    n = secs(0.35)
    out = np.zeros((n, 2))
    s = gun_shot(r, 1.6, 0.9)
    mix_at(out, stereo(s), 0)
    spin = osc(np.linspace(30, 56, n), n, 'saw')
    mix_at(out, stereo(lp(spin, 400) * env_exp(n, 0.1) * 0.15), 0)
    return saturate(out, 1.3)


def gun_tail(r, v):
    n = secs(1.8)
    out = np.zeros((n, 2))
    s = gun_shot(r, 1.2)
    mix_at(out, stereo(s), 0)
    bolt = modal(secs(0.2), [(240, 0.05, 1), (610, 0.03, 0.6), (1450, 0.02, 0.4)], r)
    mix_at(out, stereo(bolt * 0.6), secs(0.03))
    spin = osc(np.linspace(56, 12, secs(0.6)), secs(0.6), 'saw')
    mix_at(out, stereo(lp(spin, 300) * np.linspace(0.12, 0, secs(0.6))), secs(0.02))
    ir = make_ir(1.6, rng(77), decay_s=1.2, damp_hz=(6000, 800), early=[(0.21, 0.5), (0.47, 0.3), (0.83, 0.2)])
    out = convolve(out, ir, wet=0.25)[:n]
    return out


def gun_crack(r, v):
    n = secs(0.5)
    k = secs(r.uniform(0.0012, 0.0022))
    y = np.zeros(n)
    y[:k] = np.linspace(1, -1, k)
    y = hp(y, 200)
    whiz = bp(white(r, secs(0.08)), 2000, 7000) * env_points(secs(0.08), [(0, 0), (0.07, 1), (0.08, 0)]) * 0.15
    y = np.concatenate([whiz, y])[:n]
    ir = make_ir(0.5, r, decay_s=0.3, damp_hz=(7000, 1500), early=[(0.04 + 0.02 * v, 0.5)])
    out = convolve(y, ir, wet=0.2)[:n]
    return mono(out)


def aaa_burst(r, v):
    """Distant twin-barrel AAA: uneven bursts of deep thumps with slap echo."""
    n = secs(2.2)
    y = np.zeros(n)
    shots = int(r.integers(5, 10))
    pos = 0
    for i in range(shots):
        k = secs(0.25)
        t = t_axis(k)
        s = osc(60 * np.exp(-t / 0.03) + 40, k) * env_exp(k, 0.06, 0.002) * 1.3
        s += lp(white(r, k), 1400) * env_exp(k, 0.02) * 0.8
        s += hp(white(r, k), 1500) * env_exp(k, 0.003) * 0.3
        mix_at(y, s * r.uniform(0.7, 1.0), pos)
        pos += int(SR / r.uniform(15, 18)) if i % 2 == 0 else int(SR / r.uniform(28, 36))
    ir = make_ir(2.0, r, decay_s=1.6, damp_hz=(3000, 500), early=[(0.3, 0.6), (0.71, 0.4), (1.2, 0.25)])
    return mono(convolve(saturate(y, 1.4), ir, wet=0.45)[:n])


