def hit_airframe(r, v):
    n = secs(1.3)
    t = t_axis(n)
    modes = [(r.uniform(260, 340), 0.12, 1), (r.uniform(610, 720), 0.08, 0.8), (r.uniform(1150, 1350), 0.05, 0.6),
             (r.uniform(2100, 2600), 0.03, 0.5), (r.uniform(3700, 4300), 0.02, 0.35), (r.uniform(5200, 6800), 0.012, 0.25)]
    clang = modal(n, modes, r)
    crunch = bp(white(r, n), 400, 5000) * env_exp(n, 0.03, 0.0005) * 1.4
    thud = osc(90 * np.exp(-t / 0.02) + 50, n) * env_exp(n, 0.06) * 1.2
    y = saturate(clang * 0.7 + crunch + thud, 2.0)
    rattle = np.zeros(n)
    for i in range(10):
        s = modal(secs(0.08), [(r.uniform(1500, 4500), 0.01, 1)], r)
        mix_at(rattle, s * r.uniform(0.05, 0.2), secs(r.uniform(0.05, 0.7)))
    y += rattle
    return stereo(y, np.roll(y, 97))


def impact_metal(r, v):
    n = secs(0.45)
    modes = [(r.uniform(1800, 2600), 0.05, 1), (r.uniform(3300, 4200), 0.03, 0.7), (r.uniform(5200, 7000), 0.02, 0.5)]
    y = modal(n, modes, r) * 0.6 + hp(white(r, n), 1500) * env_exp(n, 0.004) * 1.2
    y += lp(white(r, n), 800) * env_exp(n, 0.01) * 0.5
    return saturate(y, 1.5)


def impact_dirt(r, v):
    n = secs(0.6)
    t = t_axis(n)
    thud = osc(80 * np.exp(-t / 0.02) + 45, n) * env_exp(n, 0.04) * 1.0
    spray = bp(white(r, n), 500, 6000) * env_points(n, [(0, 0), (0.005, 1), (0.08, 0.4), (0.6, 0)])
    grit = hp(crackle(r, n, 600, alpha=3), 1200)
    grit = grit / (np.std(grit) + 1e-9) * env_points(n, [(0, 0), (0.02, 0.3), (0.6, 0)]) * 0.3
    return saturate(thud + spray * 0.7 + grit, 1.4)


