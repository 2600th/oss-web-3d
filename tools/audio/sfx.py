# ================================================================ missiles
def motor_src(r, n, heavy=0.0):
    nz = colored(r, n, -1.5)
    x = bp(nz, 400 - 200 * heavy, 7000 - 2500 * heavy, 2)
    x = peak_eq(x, 2200 - 900 * heavy, 6, 1.0)
    cr = hp(crackle(r, n, 500, alpha=1.8), 1000)
    cr /= np.std(cr) + 1e-9
    scream = osc(2800 * (1 + 0.01 * smooth_noise(r, n, 5)), n) * 0.12
    flutter = 1 + 0.2 * smooth_noise(r, n, 25)
    low = lp(brown(r, n), 200, 2) * heavy * 1.5
    return (x + 0.4 * cr + scream) * flutter + low


def missile_launch(r, v):
    n = secs(2.8)
    t = t_axis(n)
    clunk = modal(secs(0.15), [(180, 0.04, 1), (430, 0.03, 0.7), (1150, 0.02, 0.5), (2600, 0.01, 0.3)], r)
    ign = hp(white(r, n), 300) * env_points(n, [(0, 0), (0.06, 0), (0.08, 1.4), (0.3, 0.6), (1, 0)])
    src = motor_src(r, n + secs(1))
    # pulling away: doppler drop + distance
    away = 1 / (1 + (np.maximum(0, t - 0.1) * 6) ** 1.3)
    rate = np.interp(t, [0, 0.1, 0.6, 2.8], [1.0, 1.0, 0.86, 0.8])
    pos = np.cumsum(rate)
    motor = np.interp(pos, np.arange(len(src)), src)
    motor = sweep_filter(motor, 'lp', np.interp(t, [0, 0.4, 2.8], [12000, 5000, 1500]), block=256)
    motor *= env_points(n, [(0, 0), (0.08, 0), (0.12, 1), (2.8, 1)]) * away
    whoosh = bp(white(r, n), 600, 4000) * env_points(n, [(0, 0), (0.1, 0), (0.25, 0.8), (0.9, 0)])
    y = np.zeros(n)
    mix_at(y, clunk * 0.8, 0)
    y += ign * 0.5 + motor * 1.0 + whoosh * 0.6
    y = saturate(y, 1.4)
    return stereo(y, np.roll(y, secs(0.0025)))


def sam_launch(r, v):
    n = secs(5.0)
    t = t_axis(n)
    boom = osc(60 * np.exp(-t / 0.08) + 30, n) * env_exp(n, 0.4, 0.005) * 1.4
    blast = lp(brown(r, n), 700, 2) * env_points(n, [(0, 0), (0.02, 1), (0.5, 0.4), (2, 0)]) * 1.3
    src = motor_src(r, n + secs(1), heavy=1.0)
    rate = np.interp(t, [0, 1, 5], [1, 0.92, 0.82])
    motor = np.interp(np.cumsum(rate), np.arange(len(src)), src)
    motor = sweep_filter(motor, 'lp', np.interp(t, [0, 0.5, 5], [9000, 4000, 900]), block=256)
    motor *= env_points(n, [(0, 0), (0.05, 1), (1.5, 0.7), (5, 0)])
    y = saturate(boom + blast + motor, 1.6)
    out = stereo(y, np.roll(y, secs(0.003)))
    ir = make_ir(3.0, r, decay_s=2.6, damp_hz=(5000, 600), early=[(0.4, 0.5), (1.1, 0.35)])
    return convolve(out, ir, wet=0.25)[:n]


def missile_pass(r, v):
    n = secs(2.4)
    src = motor_src(r, n * 2)
    y, _ = passby(src, speed=[520, 610][v % 2], miss=[25, 45][v % 2], t_closest=0.9, n=n)
    return y


def flare_pop(r, v):
    n = secs(1.1)
    t = t_axis(n)
    pop = hp(white(r, n), 500) * env_exp(n, 0.004, 0.0002) * 1.6
    thump = osc(140 * np.exp(-t / 0.015) + 80, n) * env_exp(n, 0.03) * 0.9
    fizz = hp(white(r, n), 2500) * env_points(n, [(0, 0), (0.02, 0.5), (0.3, 0.25), (1.1, 0)])
    sizzle = hp(crackle(r, n, 900, alpha=2.5), 1500)
    sizzle = sizzle / (np.std(sizzle) + 1e-9) * env_points(n, [(0, 0), (0.03, 0.3), (1.1, 0)]) * 0.4
    return saturate(pop + thump + fizz * 0.6 + sizzle, 1.3)


