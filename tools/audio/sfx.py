def radio_squelch(r, v, close=False):
    n = secs(0.22 if close else 0.12)
    nz = bp(white(r, n), 500, 3500, 2)
    e = env_points(n, [(0, 0), (0.003, 1), (0.05 if close else 0.02, 0.6), (n / SR, 0)])
    click = np.zeros(n)
    click[:secs(0.002)] = np.hanning(secs(0.002)) * (1 if v % 2 else -1)
    tone = osc(1150 if not close else 980, n) * env_exp(n, 0.04) * 0.2 if v % 2 == 0 else 0
    return saturate((nz * e * 0.8 + click * 1.0 + tone) * 1.2, 2.0)


def radio_static(r, n_unused=None):
    n = secs(3.4)
    nz = bp(white(r, n + secs(0.3)), 400, 3600, 2) * (0.7 + 0.3 * smooth_noise(r, n + secs(0.3), 6))
    cr = crackle(r, n + secs(0.3), 40, alpha=1.5)
    cr = bp(cr, 500, 4000) / (np.std(cr) + 1e-9) * 0.2
    x = nz + cr
    return make_loop(x, n, secs(0.3))


def ui_tone(r, v, kind):
    if kind == 'click':
        n = secs(0.06)
        y = modal(n, [(2400, 0.006, 1), (5300, 0.004, 0.5)], r) + hp(white(r, n), 3000) * env_exp(n, 0.0015) * 0.5
    elif kind == 'hover':
        n = secs(0.05)
        y = osc(3100, n) * env_exp(n, 0.012, 0.002) * 0.5
    elif kind == 'confirm':
        n = secs(0.45)
        y = np.zeros(n)
        for i, (f, d) in enumerate([(880, 0), (1318.5, 0.07)]):
            k = n - secs(d)
            mix_at(y, additive(f, k, [(1, 1), (2, 0.3), (3, 0.12)]) * env_exp(k, 0.12, 0.003) * 0.6, secs(d))
        y += hp(white(r, n), 4000) * env_exp(n, 0.002) * 0.3
    elif kind == 'back':
        n = secs(0.3)
        y = np.zeros(n)
        for f, d in [(987.8, 0), (659.3, 0.06)]:
            k = n - secs(d)
            mix_at(y, additive(f, k, [(1, 1), (2, 0.25)]) * env_exp(k, 0.07, 0.003) * 0.55, secs(d))
    elif kind == 'error':
        n = secs(0.35)
        y = additive(220, n, [(1, 1), (3, 0.4), (5, 0.2)]) * env_points(n, [(0, 0), (0.005, 1), (0.12, 0.8), (0.14, 0), (0.18, 0), (0.19, 0.8), (0.33, 0.6), (0.35, 0)]) * 0.4
    elif kind == 'kill':
        n = secs(0.7)
        y = np.zeros(n)
        for f, d in [(1174.7, 0), (1760, 0.05), (2349.3, 0.1)]:
            k = n - secs(d)
            mix_at(y, additive(f, k, [(1, 1), (2.76, 0.2), (5.4, 0.08)]) * env_exp(k, 0.15, 0.002) * 0.45, secs(d))
    elif kind == 'hit':
        n = secs(0.09)
        y = modal(n, [(1600, 0.02, 1), (3900, 0.012, 0.5)], r) * 0.7 + hp(white(r, n), 2000) * env_exp(n, 0.003) * 0.6
    ir = make_ir(0.6, rng(5), decay_s=0.4, damp_hz=(9000, 3000))
    return mono(convolve(y, ir, wet=0.12)[:len(y) + secs(0.15)])


def amb_wind_src(r, n):
    out = np.zeros((n, 2))
    gust = 0.55 + 0.45 * (0.5 + 0.5 * smooth_noise(r, n, 0.25))
    for c in range(2):
        base = lp(pink(r, n), 900, 2)
        whistle = np.zeros(n)
        for f0 in (430, 610, 870):
            fc = f0 * (1 + 0.15 * smooth_noise(r, n, 0.3))
            nz = white(r, n)
            w = sweep_filter(nz, 'bp', fc, block=512, order=2)
            whistle += w * (0.5 + 0.5 * smooth_noise(r, n, 0.2)) * 0.12
        out[:, c] = (base + whistle) * gust
    return out


def cloud_src(r, n):
    out = np.zeros((n, 2))
    for c in range(2):
        out[:, c] = lp(white(r, n), 2400, 2) * (1 + 0.3 * smooth_noise(r, n, 6)) + lp(brown(r, n), 200, 2) * 0.4
    return out


