def render(only=None):
    meta = {}
    total = 0
    for sid, (fn, variants, loop, ch, norm) in SFX.items():
        if only and not any(sid.startswith(o) for o in only):
            continue
        files = []
        for v in range(variants):
            # deterministic per id/variant (python's hash() is salted)
            r = rng(sum(map(ord, sid)) * 131 + v * 7919)
            x = fn(r, v)
            x = x if ch == 2 else mono(x)
            if ch == 2 and x.ndim == 1:
                x = stereo(x)
            # Nothing above 17 kHz survives distance/air absorption or 48 kbps Opus;
            # removing it also stops codec overshoot on the steepest transients.
            # Loops are filtered circularly so the seam stays continuous.
            # Sub-20 Hz content is removed too: it is inaudible, eats headroom,
            # and Opus' DC-reject filter would otherwise reshape it at loop seams.
            if loop:
                k = min(len(x), secs(1.0))
                x = hp(lp(np.concatenate([x[-k:], x]), 17000, 4), 20, 2)[k:]
            else:
                x = hp(lp(x, 17000, 4), 20, 2)
            if not loop:
                x = fade(x, 0.0005, 0.03)
                # trim trailing silence
                m = np.abs(mono(x))
                nz = np.nonzero(m > 1e-4 * m.max())[0]
                x = x[:nz[-1] + secs(0.02)] if len(nz) else x
            if norm[0] == 'peak':
                x = normalize_peak(x, norm[1])
            else:
                # loudness-normalise; tame the remaining peaks with a look-ahead
                # limiter (circular for loops so the seam stays clean)
                x = normalize_lufs(x, norm[1])
                if true_peak_db(x) > -1:
                    x = limiter(x, -1.0, release_s=0.12, circular=loop)
            name = sid if variants == 1 else f'{sid}_{v + 1}'
            wav = os.path.join(BUILD, name + '.wav')
            write_wav(wav, x)
            kb = 48 if ch == 1 else 80
            if sid.startswith('ui_') or sid.startswith('radio'):
                kb = 40
            sw, sa, info = encode(x, os.path.join(OUT, name), ch, kb, 96 if ch == 1 else 128, loop=loop, tmp_dir=BUILD)
            x = x * info['gain']
            total += sw
            entry = {'file': name, 'dur': round(len(x) / SR, 4), 'samples': len(x), 'ch': ch,
                     'lufs': round(lufs(x), 1), 'peak': round(peak_db(x), 2), 'tp': round(true_peak_db(x), 2),
                     'webm': sw, 'm4a': sa, 'codecTrimDb': round(20 * np.log10(info['gain']), 2)}
            if loop:
                entry['loopStart'] = info['loopStart']
                entry['loopEnd'] = info['loopEnd']
            if loop:
                entry['seam'] = [round(s, 2) for s in seam_error(x)]
            files.append(entry)
            print(f'{name:22s} {len(x) / SR:6.2f}s  LUFS {entry["lufs"]:6.1f}  peak {entry["peak"]:6.2f}  {sw / 1024:6.1f} KB')
        meta[sid] = {'loop': loop, 'variants': files}
    return meta, total


if __name__ == '__main__':
    only = sys.argv[1:] or None
    meta, total = render(only)
    path = os.path.join(BUILD, 'sfx_meta.json')
    old = json.load(open(path)) if os.path.exists(path) and only else {}
    old.update(meta)
    json.dump(old, open(path, 'w'), indent=1)
    print(f'webm total this run: {total / 1024:.0f} KB')
