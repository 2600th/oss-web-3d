def exp_transient(r, v):
    n = secs(0.7)
    t = t_axis(n)
    crack = hp(white(r, n), 900, 2) * env_exp(n, 0.012, 0.0004)
    body = lp(white(r, n), 3000, 2) * env_exp(n, 0.05, 0.001)
    k = secs(r.uniform(0.002, 0.004))
    nw = np.zeros(n)
    nw[:k] = np.linspace(1, -1, k)
    sub = osc(110 * np.exp(-t / 0.03) + 40, n) * env_exp(n, 0.08)
    y = saturate(crack * 1.5 + body + nw * 1.2 + sub * 0.8, 2.2)
    return stereo(y, np.roll(y, secs(0.0007)))


def exp_body(r, v, size='large'):
    big = size == 'large'
    n = secs(3.2 if big else 1.8)
    t = t_axis(n)
    dec = 0.9 if big else 0.45
    out = np.zeros((n, 2))
    for c in range(2):
        rumble = lp(brown(r, n), 380 if big else 600, 3) * env_points(n, [(0, 0), (0.02, 1), (dec, 0.35), (n / SR, 0)])
        fire = bp(pink(r, n), 150, 2200, 2) * env_points(n, [(0, 0), (0.04, 0.8), (dec * 0.6, 0.3), (dec * 2, 0)])
        out[:, c] = rumble * 1.6 + fire * 0.7
    f = (75 if big else 95) * np.exp(-t / 0.12) + (30 if big else 42)
    sub = osc(f, n) * env_exp(n, dec * 0.5, 0.003) * (1.6 if big else 1.0)
    out += stereo(sub)
    return saturate(out * 0.9, 2.0)


def exp_tail(r, v):
    """Rolling 'thunder' tail with discrete valley-wall returns."""
    n = secs(6.0)
    out = np.zeros((n, 2))
    for c in range(2):
        base = lp(brown(r, n), 320, 3) * env_points(n, [(0, 0), (0.15, 1), (1.2, 0.5), (6, 0)])
        out[:, c] = base * (1 + 0.6 * smooth_noise(r, n, 3))
    for t0, g in [(0.45, 0.8), (0.95, 0.6), (1.6, 0.5), (2.3, 0.35), (3.1, 0.25), (4.0, 0.15)]:
        t0 += r.uniform(-0.1, 0.1)
        k = secs(0.9)
        bump = lp(brown(r, (k)), 260, 3) * env_points(k, [(0, 0), (0.06, 1), (0.9, 0)])
        mix_at(out, stereo(bump * g, np.roll(bump, 800) * g * r.uniform(0.6, 1.0)), secs(t0))
    return out


def exp_debris(r, v):
    n = secs(3.2)
    out = np.zeros((n, 2))
    count = 70
    for i in range(count):
        tt = 0.15 + (r.random() ** 1.7) * 2.6
        k = secs(0.25)
        if r.random() < 0.55:
            modes = [(r.uniform(900, 2400) * m, r.uniform(0.01, 0.06) / m, 1 / m) for m in (1, 1.53, 2.31, 3.1)]
            s = modal(k, modes, r)
        else:
            s = bp(white(r, k), 300, 3000) * env_exp(k, 0.015)
        g = r.uniform(0.1, 0.5) * (1 - tt / 3.0)
        p = r.uniform(0, 1)
        mix_at(out, stereo(s * g * (1 - p), s * g * p), secs(tt))
    patter = bp(white(r, n), 800, 5000) * env_points(n, [(0, 0), (0.3, 0.3), (1.5, 0.15), (3.2, 0)]) * 0.15
    return out + stereo(patter, np.roll(patter, 333))


